// long long arithmetic, comparisons and conversions (via the runtime library).
// RUN: %cc %s -o %t && %t
// REQUIRES: i386, i386-run

int printf(const char *, ...);
long long vals[] = { 0, 1, -1, 2, -2, 1000000007LL, -999999999999LL, 0x7fffffffffffffffLL,
                     -0x7fffffffffffffffLL - 1, 0x100000000LL, 0xffffffffLL, 123456789012345LL };
#define N (sizeof(vals)/sizeof(vals[0]))
long long ladd(long long a, long long b) { return a + b; }
unsigned long long uhalf(unsigned long long a) { return a / 2 + a % 7; }
int main(void)
{   unsigned i, j;
    for (i = 0; i < N; i++) {
        long long a = vals[i];
        printf("%lld %lld %lld %llu %lld %lld %d\n", a, -a, ~a, uhalf(a), a << (i % 40),
               a >> (i % 40), (int)a);
        printf("%g %lld %lld\n", (double)a, (long long)(double)(a / 1024), (long long)(-2.5e15 / (i + 1)));
        for (j = 0; j < N; j++) {
            long long b = vals[j];
            printf("%lld %lld %lld %d%d%d%d%d%d %d%d%d%d", ladd(a, b), a - b, a * b,
                   a < b, a <= b, a == b, a != b, a >= b, a > b,
                   (unsigned long long)a < (unsigned long long)b,
                   (unsigned long long)a > (unsigned long long)b,
                   (unsigned long long)a <= (unsigned long long)b,
                   (unsigned long long)a >= (unsigned long long)b);
            if (b != 0 && !(b == -1 && a == vals[8]))
                printf(" %lld %lld %llu %llu", a / b, a % b,
                       (unsigned long long)a / (unsigned long long)b,
                       (unsigned long long)a % (unsigned long long)b);
            printf(" %lld %lld %lld\n", a & b, a | b, a ^ b);
        }
    }
    return 0;
}

