// Integer arithmetic, division, remainder and shifts.
// RUN: %cc %s -o %t && %t
// REQUIRES: i386, i386-run

int printf(const char *, ...);
int divs(int a, int b) { return a / b; }
int rems(int a, int b) { return a % b; }
unsigned divu(unsigned a, unsigned b) { return a / b; }
unsigned remu(unsigned a, unsigned b) { return a % b; }
int shl(int a, int b) { return a << b; }
int sar(int a, int b) { return a >> b; }
unsigned shr(unsigned a, int b) { return a >> b; }
int mixed(int a, int b, int c) { return (a * b - c) ^ (a | c) & ~b; }
int sub3(int a, int b) { return b - a; }
int neg(int a) { return -a; }
int main(void)
{   int vals[] = { 0, 1, -1, 7, -7, 100, -100, 12345, -98765, 0x7fffffff };
    int i, j;
    for (i = 0; i < 10; i++)
        for (j = 0; j < 10; j++) {
            int a = vals[i], b = vals[j];
            printf("%d %d: %d %d %d", a, b, mixed(a, b, i), sub3(a, b), neg(a));
            if (b != 0 && !(a == (int)0x80000000 && b == -1))
                printf(" %d %d %u %u", divs(a, b), rems(a, b),
                       divu(a, b), remu(a, b));
            printf(" %d %d %u\n", shl(a, j), sar(a, j), shr(a, j));
        }
    return 0;
}

